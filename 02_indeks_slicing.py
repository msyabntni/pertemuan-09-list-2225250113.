
# Latihan 2: Indeks dan Slicing

# Input: Menyimpan enam nilai ke dalam list.
nilai = [75, 80, 65, 90, 88, 70]

# Proses: Mengakses elemen menggunakan indeks dan slicing.
elemen_pertama = nilai[0]
elemen_terakhir = nilai[-1]
tiga_elemen_awal = nilai[:3]
indeks_1_sampai_3 = nilai[1:4]

# Output: Menampilkan hasil indeks dan slicing.
print(f"Elemen pertama = {elemen_pertama}")
print(f"Elemen terakhir = {elemen_terakhir}")
print(f"Tiga elemen awal = {tiga_elemen_awal}")
print(f"Elemen indeks 1 sampai 3 = {indeks_1_sampai_3}")
    