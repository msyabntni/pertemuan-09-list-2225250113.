
# Latihan 3: Manipulasi List

# Input: Menyimpan tiga nilai awal ke dalam list.
nilai = [75, 80, 65]

# Proses: Mengubah, menambah, menyisipkan, dan menghapus data.
nilai[1] = 82
nilai.append(90)
nilai.insert(1, 70)
nilai.remove(65)

# Output: Menampilkan list setelah dimanipulasi.
print(f"List setelah manipulasi = {nilai}")
    