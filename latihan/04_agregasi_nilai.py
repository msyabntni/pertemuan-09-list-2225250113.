
# Latihan 4: Agregasi Nilai

# Input: Menyimpan lima nilai ke dalam list.
nilai = [75, 80, 65, 90, 88]

# Proses: Menghitung total, rata-rata, minimum, dan maksimum.
total = sum(nilai)
rata_rata = total / len(nilai)
minimum = min(nilai)
maksimum = max(nilai)

# Output: Menampilkan hasil perhitungan statistik.
print(f"Total = {total}")
print(f"Rata-rata = {rata_rata:.2f}")
print(f"Minimum = {minimum}")
print(f"Maksimum = {maksimum}")
    